// emit.js DATADIR > calendar_data.rs: the calendar locales (c-TAG.json from cinfer.js) and the
// table calendars (tables.json from derive.js) as djs's intl/date/calendar_data.rs.
const fs = require('fs'), path = require('path');
const dir = process.argv[2];
const CALS = ["gregory", "buddhist", "roc", "japanese", "persian", "islamic-civil", "islamic-tbla", "islamic-umalqura", "islamic", "islamic-rgsa", "hebrew", "indian", "coptic", "ethiopic", "ethioaa", "chinese", "dangi", "iso8601"];
const T = JSON.parse(fs.readFileSync(path.join(__dirname, 'tables.json')));
const rs = s => '"' + [...s].map(c => c === '\\' ? '\\\\' : c === '"' ? '\\"' : c.codePointAt(0) < 32 ? '\\u{' + c.codePointAt(0).toString(16) + '}' : c).join('') + '"';
const pats = [], pidx = new Map();
// pattern marks travel as U+E001..U+E004 (U+0001 separates a Spec's entries)
const P = p => { if (p === null || p === undefined) return 65535; p = p.replace(/[\u0001-\u0004]/g, c => String.fromCharCode(0xe000 + c.charCodeAt(0))); if (!pidx.has(p)) { pidx.set(p, pats.length); pats.push(p); } return pidx.get(p); };
const rows = [], ridx = new Map();
const R = (arr, len = 864) => { const out = []; for (let i = 0; i < len; i += 16) { const row = arr.slice(i, i + 16).map(P); const k = row.join(','); if (!ridx.has(k)) { ridx.set(k, rows.length); rows.push(row); } out.push(ridx.get(k)); } return out; };
const files = fs.readdirSync(dir).filter(f => /^c-.*\.json$/.test(f)).sort();
const locs = [];
for (const f of files) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f)));
  if (d.bad.length) throw new Error(f + ' has ' + d.bad.length + ' uninferred patterns');
  const base = d.tag.split('-u-')[0], key = base === 'en-US' ? 'en' : base;
  const n = d.names, cal = CALS.indexOf(n.cal);
  const fill = arr => {
    arr = arr.slice();
    const luni = n.cal === 'chinese' || n.cal === 'dangi';
    if (luni) { // leap month names nobody sampled (1900-2100 has none) follow the sampled ones' affix
      const k = arr.findIndex((v, i) => i >= 12 && v); let pre = '', suf = '';
      if (k >= 0) { const r = arr[k - 12], v = arr[k]; if (v.startsWith(r)) suf = v.slice(r.length); else if (v.endsWith(r)) pre = v.slice(0, v.length - r.length); }
      for (let i = 12; i < 24; i++) if (!arr[i]) arr[i] = pre + arr[i - 12] + suf;
    }
    return arr.map(v => v || '');
  };
  const m = n.months;
  locs.push({cal, key, tag: d.tag, months: [m.Mlong, m.Mshort, m.Mnarrow, m.Llong, m.Lshort, m.Lnarrow].map(fill), eras: n.eras.map(e => e.map(v => v || '')), leap: n.leapNum || '', years: n.yearNames || [],
    date: R(d.date), datez: R(d.datez), styles: d.styles.map(P), glue: d.glue, style_glue: d.style_glue,
    time: d.time ? {time: R(d.time, 3024), timez: R(d.timez, 3024), styles: d.style_time.map(r => r.map(P))} : null});
}
const strs = a => '&[' + a.map(rs).join(', ') + ']';
let o = '// Generated by scripts/intl-cal/emit.js from node 22.23.5\'s ICU (scripts/intl-cal/README.md): do not edit.\n\nuse super::calendar::{CalLocale, TimeTable};\n\n';
o += 'pub(super) static CAL_PATTERNS: [&str; ' + pats.length + '] = [' + pats.map(rs).join(', ') + '];\n\n';
o += 'pub(super) static CAL_ROWS: [[u16; 16]; ' + rows.length + '] = [' + rows.map(r => '[' + r.join(', ') + ']').join(', ') + '];\n\n';
o += 'pub(super) static CAL_LOCALES: [CalLocale; ' + locs.length + '] = [\n';
for (const l of locs) o += '    // ' + l.tag + '\n    CalLocale { cal: ' + l.cal + ', key: ' + rs(l.key) + ', months: [' + l.months.map(strs).join(', ') + '], eras: [' + l.eras.map(strs).join(', ') + '], leap: ' + rs(l.leap) + ', years: ' + strs(l.years) +
  ', date: [' + l.date.join(', ') + '], datez: [' + l.datez.join(', ') + '], styles: [' + l.styles.join(', ') + '], glue: [' + l.glue.map(rs).join(', ') + '], style_glue: [' + l.style_glue.map(rs).join(', ') + '], time: ' + (l.time ? 'Some(&TimeTable { time: [' + l.time.time.join(', ') + '], timez: [' + l.time.timez.join(', ') + '], styles: [' + l.time.styles.map(r => '[' + r.join(', ') + ']').join(', ') + '] })' : 'None') + ' },\n';
o += '];\n\n';
o += '/// Chinese and Korean lunisolar years from 1600 to 2400: (first day, days since 1970; 30-day months mask; the\n/// regular month a leap month follows, or 0; related gregorian year).\n';
for (const c of ['chinese', 'dangi']) o += 'pub(super) static ' + c.toUpperCase() + ': &[(i32, u16, u8, i16)] = &[' + T[c].map(y => '(' + y.join(', ') + ')').join(', ') + '];\n\n';
o += '/// Umm al-Qura and astronomical (islamic, islamic-rgsa) hijri years: (year, first day, 30-day months mask).\n';
o += 'pub(super) static HIJRI: [&[(i16, i32, u16)]; 2] = [' + ['islamic-umalqura', 'islamic'].map(c => '&[' + T[c].map(y => '(' + y.join(', ') + ')').join(', ') + ']').join(', ') + '];\n';
process.stdout.write(o);
console.error('locales', locs.length, 'patterns', pats.length, 'rows', rows.length);
