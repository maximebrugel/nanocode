// rangeemit.js : Rust tables for Intl.DateTimeFormat formatRange (intl/date/range_data.rs) from the
// r-LOC (range.js), rzf-LOC (rangez.js, rzfilter.js), tp-LOC (tpat.js) and t-LOC (infer.js) files of every locale; rangemodel.js is the
// algorithm they feed. Usage: node rangeemit.js > ../../crates/djs-core/src/builtins/intl/date/range_data.rs
// (needs node 22.23.5 for the glue it reads through infer.js; run it with LOC unset).
const fs = require('fs');
const {execFileSync} = require('child_process');
const LOCS = ["de", "fr", "es", "ja", "zh", "pt-BR", "ko", "it", "ru", "nl", "pl", "tr", "ar", "hi", "id", "vi", "zh-TW", "en-GB", "en-IN", "es-MX", "fr-CA", "en-US"];
const dir = __dirname;
const lit = s => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, "\\u{$1}");
const pool = [], pidx = new Map();
const P = s => { if (!pidx.has(s)) { pidx.set(s, pool.length); pool.push(s); } return pidx.get(s); };
const pairs = [], pairIdx = new Map();
const NONE = 65535, SAME = 65534;
// an entry: "=" (SAME), a pair of patterns (index into RANGE_PAIRS), or missing (NONE)
const E = e => { if (e === "=") return SAME; if (!Array.isArray(e)) return NONE; const k = P(e[0]) * 65536 + P(e[1]); if (!pairIdx.has(k)) { pairIdx.set(k, pairs.length); pairs.push([P(e[0]), P(e[1])]); } return pairIdx.get(k); };
const rows = [], rowIdx = new Map();
const chunk = a => { const out = []; for (let i = 0; i < a.length; i += 16) { const r = a.slice(i, i + 16); while (r.length < 16) r.push(NONE); const k = r.join(","); if (!rowIdx.has(k)) { rowIdx.set(k, rows.length); rows.push(r); } out.push(rowIdx.get(k)); } return out; };
const locs = [];
for (const L of LOCS) {
  const R = JSON.parse(fs.readFileSync(dir + '/r-' + L + '.json'));
  const TP = JSON.parse(fs.readFileSync(dir + '/tp-' + L + '.json'));
  const glues = JSON.parse(execFileSync(process.execPath, [dir + '/rglue.js', L], {encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore']}));
  const dp = []; for (let k = 0; k < 864; k++) dp.push(TP.dpat[k] === undefined ? NONE : P(TP.dpat[k]));
  const tp = []; for (let z = 0; z < 7; z++) for (let k = 0; k < 3024; k++) tp.push(TP.tpat[z][k] === undefined ? NONE : P(TP.tpat[z][k]));
  const date = []; for (let k = 0; k < 864; k++) for (let l = 0; l < 4; l++) date.push(R.date[k] ? E(R.date[k][l]) : NONE);
  const time = []; for (const tab of [R.time, ...R.timez]) for (let k = 0; k < 252; k++) for (let l = 0; l < 5; l++) time.push(tab[k] ? E(tab[k][l]) : NONE);
  const st = [];
  for (let d = 0; d < 4; d++) for (let l = 0; l < 4; l++) st.push(E(R.sdate[d][l]));
  for (let c = 0; c < 7; c++) for (let t = 0; t < 4; t++) for (let l = 0; l < 8; l++) st.push(E(R.stime[c][t][l]));
  for (let d = 0; d < 4; d++) for (let c = 0; c < 7; c++) for (let t = 0; t < 4; t++) for (let l = 0; l < 8; l++) st.push(E(R.sboth[d][c][t][l]));
  const tpf = []; for (let z = 0; z < 7; z++) for (let k = 0; k < 3024; k++) { const v = TP.tpatf && TP.tpatf[z][k]; tpf.push(v === undefined ? NONE : P(v)); }
  const dpn = []; for (let k = 0; k < 864; k++) { const v = TP.dpatn && TP.dpatn[k]; dpn.push(v === undefined ? NONE : P(v)); }
  // date interval entries with each zone name kind (rangez.js): 6 kinds x 864 x levels G y M d
  const RZ = JSON.parse(fs.readFileSync(dir + '/rzf-' + L + '.json'));
  const dz = []; for (let z = 0; z < 6; z++) for (let k = 0; k < 864; k++) for (let l = 0; l < 4; l++) dz.push(RZ.datez[z][k] ? E(RZ.datez[z][k][l]) : NONE);
  locs.push({L, sep: R.sep, glues, gm: TP.gm, dp: chunk(dp), tp: chunk(tp), date: chunk(date), time: chunk(time), st: chunk(st), tpf: chunk(tpf), dpn: chunk(dpn), dz: chunk(dz)});
}
let out = "// Generated by scripts/intl-dtf/rangeemit.js from node 22.23.5's formatRangeToParts: do not edit.\n\n";
out += "use super::range::RangeLocale;\n\n";
const arr = a => "[" + a.join(", ") + "]";
for (const l of locs) {
  const id = "R_" + l.L.toUpperCase().replace("-", "_");
  out += "static " + id + ": [u16; " + (l.dp.length + l.tp.length + l.date.length + l.time.length + l.st.length + l.tpf.length + l.dpn.length + l.dz.length) + "] = " + arr([...l.dp, ...l.tp, ...l.date, ...l.time, ...l.st, ...l.tpf, ...l.dpn, ...l.dz]) + ";\n";
}
out += "\n/// Every locale's range tables, in DATE_LOCALES order, then en-US.\npub(super) static RANGE_LOCALES: &[RangeLocale] = &[\n";
for (const l of locs) out += "    RangeLocale { sep: " + lit(l.sep) + ", glue: [" + l.glues.map(lit).join(", ") + "], gm: " + lit(l.gm) + ", rows: &R_" + l.L.toUpperCase().replace("-", "_") + " },\n";
out += "];\n";
out += "\n/// Rows of 16 cells (pattern or pair indices, u16::MAX for none, u16::MAX - 1 for the start alone).\npub(super) static RANGE_ROWS: &[[u16; 16]] = &[" + rows.map(arr).join(", ") + "];\n";
out += "\n/// Interval patterns: (first half, second half) indices into RANGE_PATTERNS.\npub(super) static RANGE_PAIRS: &[(u16, u16)] = &[" + pairs.map(p => "(" + p[0] + ", " + p[1] + ")").join(", ") + "];\n";
let n = 0; const ends = pool.map(x => n += Buffer.byteLength(x));
out += "\npub(super) static RANGE_PATTERNS_TEXT: &str = " + lit(pool.join("")) + ";\npub(super) static RANGE_PATTERNS_ENDS: &[u32] = &" + arr(ends) + ";\n";
process.stdout.write(out);
process.stderr.write("patterns " + pool.length + " pairs " + pairs.length + " rows " + rows.length + " bytes " + out.length + "\n");

