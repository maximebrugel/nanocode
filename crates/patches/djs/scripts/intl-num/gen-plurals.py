#!/usr/bin/env python3
"""Writes crates/djs-core/src/builtins/intl/plurdata.rs: CLDR plural rules (cardinal and ordinal)
for the languages djs evaluates by rule (text.rs rule_plural), from cldr-core's plurals.json and
ordinals.json at the CLDR version node 22's ICU has (process.versions.cldr, 48):
  npm pack cldr-core@48.0.0 && tar xzf cldr-core-48.0.0.tgz
  python3 gen-plurals.py package/supplemental > ../../crates/djs-core/src/builtins/intl/plurdata.rs"""
import json, os, sys
LANGS = ["hu", "nb", "no", "he", "ta", "sr", "cs", "uk", "sv", "da", "ms", "ro", "bn", "el", "sw", "ur", "fil", "ca", "fa", "th", "fi"]
d = sys.argv[1]
card = json.load(open(os.path.join(d, "plurals.json")))["supplemental"]["plurals-type-cardinal"]
ordn = json.load(open(os.path.join(d, "ordinals.json")))["supplemental"]["plurals-type-ordinal"]
ORDER = ["zero", "one", "two", "few", "many", "other"]
print("// Generated by scripts/intl-num/gen-plurals.py from CLDR " + json.load(open(os.path.join(d, "../package.json")))["version"] + ". Do not edit.")
print("// (language, ordinal, categories as resolvedOptions lists them, rules in CLDR's syntax without")
print("// samples; a value takes the first category whose rule holds, else other)")
print("pub(super) type PluralRule = (&'static str, bool, &'static str, &'static [(&'static str, &'static str)]);")
print("pub(super) static PLURAL_RULES: &[PluralRule] = &[")
for lang in LANGS:
    for ordinal, src in ((False, card), (True, ordn)):
        rules = src[lang]
        cats = [k.split("-")[-1] for k in rules]
        rows = [(c, rules["pluralRule-count-" + c].split("@")[0].strip()) for c in ORDER if c in cats and c != "other"]
        listed = ",".join(sorted(c for c in cats if c != "other") + ["other"])
        print('    ("%s", %s, "%s", &[%s]),' % (lang, "true" if ordinal else "false", listed, ", ".join('("%s", "%s")' % r for r in rows)))
print("];")
rng = json.load(open(os.path.join(d, "pluralRanges.json")))["supplemental"]["plurals"]
print("// CLDR's plural ranges (start, end, result) for those languages; a pair it lacks is other.")
print("pub(super) static PLURAL_RANGES_CLDR: &[(&str, &str, &str, &str)] = &[")
for lang in LANGS:
    for k, v in rng.get(lang, {}).items():
        _, _, a, _, b = k.split("-")
        print('    ("%s", "%s", "%s", "%s"),' % (lang, a, b, v))
print("];")
