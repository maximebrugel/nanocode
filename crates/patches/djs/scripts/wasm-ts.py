#!/usr/bin/env python3
"""Writes builtins/webassembly.ts from builtins/wasm/runtime.js (WebAssembly for djs).

The runtime is plain JS: the builtin language has no closures or property syntax, so
webassembly.ts embeds it as a string and compiles it with %CompileFunction when the
prelude installs the namespace. Whole-line comments, indentation and blank lines are
dropped from the embedded copy.
  scripts/wasm-ts.py          write builtins/webassembly.ts
  scripts/wasm-ts.py --check  exit 1 if it is out of date
"""
import os
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src_path = os.path.join(root, "builtins/wasm/runtime.js")
out_path = os.path.join(root, "builtins/webassembly.ts")

HEAD = '''// @embed-only
// Generated by scripts/wasm-ts.py from builtins/wasm/runtime.js; do not edit.
// WebAssembly, for builds with djs-core's embed feature (the shipped wasm module's size
// counts, D020): the namespace object, filled in by builtins/wasm/runtime.js.

/**
 * The %WebAssembly% namespace object. WebAssemblyToStringTag fills it in.
 * @value globalThis.WebAssembly
 * @attributes writable configurable
 */
function WebAssemblyObject(): Obj {
  return ObjectCreate(RealmIntrinsic("ObjectPrototype"));
}

/**
 * WebAssembly [ %Symbol.toStringTag% ]. Installs off the global object come after those
 * onto it, and this file sorts last, so every builtin the runtime's top level uses exists
 * by now: it runs builtins/wasm/runtime.js, which defines the namespace's members.
 * @value WebAssembly[Symbol.toStringTag]
 * @attributes configurable
 */
function WebAssemblyToStringTag(): Str {
  const ns: Value = Get(GlobalObject(), "WebAssembly");
  const script: Obj = CompileFunction(0, "WebAssembly", WebAssemblyRuntimeSource());
  const init: Value = Call(script, GlobalObject());
  Call(init, undefined, ns);
  return "WebAssembly";
}

/** The source of builtins/wasm/runtime.js, without comments and indentation. */
function WebAssemblyRuntimeSource(): Str {
  return "'''


def render():
    lines = []
    for line in open(src_path, encoding="utf-8").read().split("\n"):
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        lines.append(s)
    body = "\n".join(lines) + "\n"
    if any(ord(c) > 0x7e for c in body):
        sys.exit("wasm-ts.py: builtins/wasm/runtime.js must be ASCII")
    esc = body.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return HEAD + esc + '";\n}\n'


def main():
    out = render()
    if "--check" in sys.argv[1:]:
        cur = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else ""
        if cur != out:
            sys.exit("builtins/webassembly.ts is out of date: run scripts/wasm-ts.py")
        return
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(out)


main()

